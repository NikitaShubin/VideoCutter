/**
 * Легенда цветов таймлайна — вторая строка подсказки к полосе, а не
 * отдельная строка интерфейса: подсказка не занимает места. Полное
 * описание цветов остаётся в справке редактора.
 */
export const TIMELINE_LEGEND =
  "Цвета: 🟩 зелёный — свободно · 🟥 красный — фрагмент · " +
  "🟧 оранжевый — фрагмент с комментарием · ⬛ затемнённый — после текущего кадра · " +
  "🟦/🟪 бирюзовый/пурпурный — выделено · ⬜ белый — текущий кадр";

/** Подсказка таймлайна: действие первой строкой, легенда — второй. */
export function timelineLegendTitle(firstLine: string): string {
  return `${firstLine}\n${TIMELINE_LEGEND}`;
}
