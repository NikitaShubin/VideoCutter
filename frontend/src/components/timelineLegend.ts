/**
 * Легенда цветов таймлайна — нижние строки подсказки к полосе, а не
 * отдельная строка интерфейса: подсказка не занимает места. Полное
 * описание цветов остаётся в справке редактора.
 */
export const TIMELINE_LEGEND = [
  "Цвета:",
  "🟩 зелёный — свободно",
  "🟥 красный — фрагмент",
  "🟧 оранжевый — фрагмент с комментарием",
  "⬛ затемнённый — после текущего кадра",
  "🟦 бирюзовый — выделено поверх свободного",
  "🟪 пурпурный — выделено поверх фрагмента",
  "⬜ белый — текущий кадр",
].join("\n");

/** Подсказка таймлайна: действие первой строкой, легенда — ниже. */
export function timelineLegendTitle(firstLine: string): string {
  return `${firstLine}\n${TIMELINE_LEGEND}`;
}
